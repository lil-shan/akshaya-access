// Usage: set -a; . ../.cloud.env; set +a; node scripts/verify_crm.mjs
import { createClient } from "../web/node_modules/@supabase/supabase-js/dist/index.mjs";
const opt = { auth: { persistSession: false } };
const sb = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_ANON_KEY, opt);
const admin = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, opt);
let fails = 0; const ok = (n, c, d = "") => { console.log(`${c ? "PASS" : "FAIL"} ${n}${!c && d ? " - " + d : ""}`); if (!c) fails++; };
let caseId, path, shot;
try {
  const s = await sb.auth.signInWithPassword({ email: process.env.CRM_TEST_EMAIL, password: process.env.CRM_TEST_PASSWORD });
  ok("sign in", !s.error, s.error?.message);
  const sv = await sb.from("services").select("id,fields").limit(50);
  ok("list services", !sv.error && sv.data.length > 0, sv.error?.message);
  const cz = await sb.from("citizens").select("id").limit(1);
  const c = await sb.from("cases").insert({ citizen_id: cz.data?.[0]?.id, service_id: sv.data[0].id, data: { _e2e: "true" } }).select("id").single();
  ok("create case", !c.error, c.error?.message); caseId = c.data?.id;
  const u = await sb.from("cases").update({ data: { _e2e: "true", note: "verify" } }).eq("id", caseId).select("data").single();
  ok("save data", u.data?.data?.note === "verify", u.error?.message);
  path = `${caseId}/uploads/verify.pdf`;
  const pdf = new Blob(["%PDF-1.4\n1 0 obj<<>>endobj\ntrailer<<>>\n%%EOF"], { type: "application/pdf" });
  const up = await sb.storage.from("case-files").upload(path, pdf, { contentType: "application/pdf" });
  ok("upload pdf", !up.error, up.error?.message);
  const d = await sb.from("documents").insert({ case_id: caseId, kind: "other", storage_path: path, source: "upload" });
  ok("documents row", !d.error, d.error?.message);
  const su = await sb.storage.from("case-files").createSignedUrl(path, 60);
  const r = su.data ? await fetch(su.data.signedUrl) : null;
  ok("read via signed url", r?.ok && (await r.text()).startsWith("%PDF"), su.error?.message);
  const bad = await sb.storage.from("case-files").upload(`${caseId}/other/x.pdf`, pdf);
  ok("upload outside uploads/ denied", !!bad.error);
  const k = await sb.from("consents").insert({ case_id: caseId, kind: "digilocker", text: "verify", channel: "crm" });
  ok("insert consent", !k.error, k.error?.message);
  const j = await sb.from("automation_jobs").insert({ case_id: caseId, kind: "digilocker_fetch", mode: "mock", status: "queued" });
  ok("insert digilocker_fetch job", !j.error, j.error?.message);
  const dk = await sb.from("consents").insert({ case_id: caseId, kind: "portal_dry_run", text: "verify", channel: "crm" });
  ok("insert portal_dry_run consent", !dk.error, dk.error?.message);
  const dj = await sb.from("automation_jobs").insert({ case_id: caseId, kind: "portal_fill", mode: "dry_run", status: "queued" }).select("id").single();
  ok("insert dry_run portal_fill job", !dj.error, dj.error?.message);
  const pr = await admin.from("job_prompts").insert({ job_id: dj.data?.id, kind: "field", prompt_text: "Mobile number registered for this login", status: "open", expires_at: new Date(Date.now() + 120000).toISOString() }).select("id").single();
  const ans = await sb.from("job_prompts").update({ answer: "9999999999", status: "answered", answered_at: new Date().toISOString() }).eq("id", pr.data?.id).eq("status", "open").select("status").single();
  ok("answer field prompt", !pr.error && ans.data?.status === "answered", pr.error?.message ?? ans.error?.message);
  const bj = await sb.from("automation_jobs").insert({ case_id: caseId, kind: "bbps_fetch", mode: "mock", status: "queued" });
  ok("insert bbps_fetch job", !bj.error, bj.error?.message);
  const pc = await sb.from("consents").insert({ case_id: caseId, kind: "payment", text: "Citizen confirmed payment of \u20b9100 (verify)", channel: "crm" });
  ok("insert payment consent", !pc.error, pc.error?.message);
  const pj = await sb.from("automation_jobs").insert({ case_id: caseId, kind: "payment_collect", mode: "mock", status: "queued" });
  ok("insert payment_collect job", !pj.error, pj.error?.message);
  const pay = await sb.from("payments").select("id").eq("case_id", caseId);
  ok("read payments", !pay.error, pay.error?.message);
  const cp = await admin.from("job_prompts").insert({ job_id: dj.data?.id, kind: "confirm", prompt_text: "Approve DigiLocker access: https://example.com/consent?x=1", status: "open", expires_at: new Date(Date.now() + 120000).toISOString() }).select("id").single();
  const ca = await sb.from("job_prompts").update({ answer: "yes", status: "answered", answered_at: new Date().toISOString() }).eq("id", cp.data?.id).eq("status", "open").select("status").single();
  ok("answer confirm prompt", !cp.error && ca.data?.status === "answered", cp.error?.message ?? ca.error?.message);
  const pp = await admin.from("job_prompts").insert({ job_id: dj.data?.id, kind: "password", prompt_text: "Thuna password", status: "open", expires_at: new Date(Date.now() + 120000).toISOString() }).select("id").single();
  const pa = await sb.from("job_prompts").update({ answer: "verify-pw", status: "answered", answered_at: new Date().toISOString() }).eq("id", pp.data?.id).eq("status", "open").select("status").single();
  ok("answer password prompt", !pp.error && pa.data?.status === "answered", pp.error?.message ?? pa.error?.message);
  const up1 = await admin.from("payments").insert({ case_id: caseId, provider: "upi_qr_demo", amount_inr: 100, status: "pending" }).select("id").single();
  const up2 = await sb.from("payments").update({ status: "confirmed" }).eq("id", up1.data?.id).eq("status", "pending").select("status").single();
  ok("mark upi_qr_demo payment confirmed", !up1.error && up2.data?.status === "confirmed", up1.error?.message ?? up2.error?.message);
  shot = `${caseId}/${dj.data?.id}/verify.png`;
  const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==", "base64");
  const sup = await admin.storage.from("case-files").upload(shot, png, { contentType: "image/png" });
  const ssu = await sb.storage.from("case-files").createSignedUrl(shot, 60);
  const sr = ssu.data ? await fetch(ssu.data.signedUrl) : null;
  ok("screenshot readable via signed url", !sup.error && sr?.ok && sr.headers.get("content-type")?.includes("image"), sup.error?.message ?? ssu.error?.message);
  const ev = await sb.from("case_events").select("id").eq("case_id", caseId);
  ok("read case_events", !ev.error, ev.error?.message);
  await sb.auth.signOut();
  const a = await sb.from("cases").select("id").limit(5);
  const an = await sb.from("services").select("id").limit(5);
  const st = await sb.storage.from("case-files").createSignedUrl(path, 60);
  ok("anon sees nothing", !a.data?.length && !an.data?.length && !st.data, "cases/services/storage leaked");
} catch (e) { ok("script error", false, e.message); }
finally {
  if (shot) await admin.storage.from("case-files").remove([shot]);
  if (path) await admin.storage.from("case-files").remove([path]);
  if (caseId) await admin.from("cases").delete().eq("id", caseId);
  console.log("cleaned up");
}
process.exit(fails ? 1 : 0);
